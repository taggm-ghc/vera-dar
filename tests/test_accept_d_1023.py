def _bundle(h, **kw):
    kw.setdefault("docs", DOCS)
    kw.setdefault("items_over", ITEMS)
    root = synth.write_bundle(h.tmp / "bundle", **kw)
    cfg = synth.synth_cfg()
    fulldoc_corpus.reset_for_tests()
    h.mp.setattr(fulldoc_corpus, "load_config", lambda *a, **k: cfg)
    h.mp.setenv("VERA_FULLDOC_BUNDLE_DIR", str(root))
    return root


def _ask(h, q=Q):
    main = h.install()
    c = TestClient(main.app)
    r = c.post("/ask", json={"question": q}, headers={"X-API-Key": "k" * 20})
    v = c.get("/version")
    return r.status_code, r.json(), v.json()


def fails(http, body, version, **kw):
    return ap.grounded_failures(http, body, version=version, expect_commit="7da574a", **kw)


