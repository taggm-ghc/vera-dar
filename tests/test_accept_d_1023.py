# ------------------------------------------------------------- persistence across fresh sessions
def _persist_to_db(h, monkeypatch):
    """Write the fixture bundle through the production writer into a SQLite file, then DELETE the bundle."""
    root = _bundle(h)
    cfg = synth.synth_cfg()
    s = wa._script()
    rows, report = s.build_plan(root, cfg, target=700)
    spec = wa._make_db(h.tmp / "db", "w")
    eng = wa._engine(spec)
    done = s.write_rows(eng, eng, rows, fulltext_loader.load_config(), report["n_spans"])
    eng.dispose()
    shutil.rmtree(root)
    url, schema = spec.split("|")
    main_path = url[len("sqlite:///"):]
    log = []
    monkeypatch.delenv("VERA_FULLDOC_BUNDLE_DIR", raising=False)
    monkeypatch.setattr(fulldoc_corpus, "load_config", lambda *a, **k: cfg)
    monkeypatch.setattr(fulldoc_db, "default_connect", lambda c, env: (lambda: SqliteRO(main_path, schema, log)))
    monkeypatch.setenv(fulldoc_corpus.DB_RUN_ID_ENV_DEFAULT, str(done["run_id"]))
    return main_path, schema, log


def _counts(main_path, schema):
    con = sqlite3.connect(main_path)
    con.execute(f"ATTACH DATABASE '{schema}' AS vera_vjay")
    n = (con.execute("SELECT count(*) FROM vera_vjay.sources").fetchone()[0],
         con.execute("SELECT count(*) FROM vera_vjay.evidence_spans").fetchone()[0])
    con.close()
    return n


def test_stored_evidence_survives_fresh_sessions(env, monkeypatch):
    main_path, schema, log = _persist_to_db(env, monkeypatch)
    before = _counts(main_path, schema)
    http, b1, v1 = _ask(env)
    assert fails(http, b1, v1, stored_doc_ids={"tsr", "wmpf"}) == [] and b1["corpus_source"] == {"kind": "db"}
    n_reads = len(log)
    assert n_reads == 2  # one sources + one spans SELECT: loaded from the store, no bundle exists
    # a second ask in the SAME process hits the in-process cache (no new DB read): that is not persistence evidence
    _ask(env)
    assert len(log) == n_reads
    # FRESH SESSION: in-process caches cleared, a new Harness and a new TestClient/app wiring, same store
    fulldoc_corpus.reset_for_tests()
    h2 = e2e.Harness(monkeypatch, env.tmp)
    h2.answer_text = ANSWER
    http, b2, v2 = _ask(h2)
    assert len(log) == n_reads + 2, "fresh session did not re-read the store"
    assert fails(http, b2, v2, stored_doc_ids={"tsr", "wmpf"}) == []
    key = lambda b: sorted((a["span_id"], a["text_sha256"]) for a in b["admitted_evidence"])  # noqa: E731
    assert key(b1) == key(b2)
    assert sorted((d["document_id"], d["text_sha256"]) for d in b1["examined_full_documents"]) == \
        sorted((d["document_id"], d["text_sha256"]) for d in b2["examined_full_documents"])
    assert _counts(main_path, schema) == before  # /ask never mutates the store


def test_neg_empty_store_is_not_an_answer(env, monkeypatch):
    """A fresh session against a store that lost its evidence must fail acceptance (guards a vacuous persistence pass)."""
    main_path, schema, log = _persist_to_db(env, monkeypatch)
    con = sqlite3.connect(main_path)
    con.execute(f"ATTACH DATABASE '{schema}' AS vera_vjay")
    con.execute("DELETE FROM vera_vjay.evidence_spans")
    con.execute("DELETE FROM vera_vjay.sources")
    con.commit()
    con.close()
    fulldoc_corpus.reset_for_tests()
    http, body, ver = _ask(env)
    assert http == 200 and body["result_kind"] != "answer"
    assert fails(http, body, ver)


def test_bundle_store_survives_cache_clear(env):
    root = _bundle(env)
    http, b1, v1 = _ask(env)
    assert fails(http, b1, v1) == []
    fulldoc_corpus.reset_for_tests()  # fresh process analogue: cache gone, files remain
    http, b2, v2 = _ask(env)
    assert fails(http, b2, v2) == [] and b2["corpus_source"] == {"kind": "bundle"}
    shutil.rmtree(root)  # store gone: no answer from a stale cache after a reset
    fulldoc_corpus.reset_for_tests()
    http, b3, v3 = _ask(env)
    assert fails(http, b3, v3)
